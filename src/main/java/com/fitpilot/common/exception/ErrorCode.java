package com.fitpilot.common.exception;

public enum ErrorCode {
    VALIDATION_ERROR(1000), AUTHENTICATION_REQUIRED(1001), ACCESS_DENIED(1002),
    USER_NOT_FOUND(10001), USERNAME_EXISTS(10002), PASSWORD_INCORRECT(10003), EMAIL_EXISTS(10004), USER_DISABLED(10005),
    EXERCISE_NOT_FOUND(20001),
    TRAINING_PLAN_NOT_FOUND(30001), TRAINING_PLAN_ALREADY_ACTIVE(30002), INVALID_TRAINING_PLAN(30003),
    WORKOUT_NOT_FOUND(40001), WORKOUT_ALREADY_COMPLETED(40002), INVALID_WORKOUT_SET(40003), WORKOUT_CANCELLED(40004),
    CONCURRENT_MODIFICATION(50001), RATE_LIMITED(50002), IDEMPOTENCY_IN_PROGRESS(50003),
    EVENT_NOT_FOUND(60001), EVENT_REPLAY_FAILED(60002),
    INTERNAL_ERROR(99999);

    private final int code;
    ErrorCode(int code) { this.code = code; }
    public int code() { return code; }
}
